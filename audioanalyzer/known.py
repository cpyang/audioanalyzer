"""Known-source library and cross-corpus recurrence (REQUIREMENTS.md FR-7.2, FR-7.3).

``known.toml`` turns "100.2 Hz, UNKNOWN" into "100 Hz — UPS/PSU double-mains ripple (known)"
which is the difference between a lead and a dead end.  The library is deliberately tiny and
plain text: it is meant to be edited by whoever walks the site, not regenerated by a model.

Recurrence answers the other half of "where is it coming from": a noise that appears at
07:04, 15:04 and 23:04 is on a schedule, and a schedule has an owner.  With one day of audio —
which is all this corpus has — day-of-week correlation is not merely uncomputed, it is
*uncomputable*, and the code says so rather than returning an empty dict that reads like
"nothing found".
"""

from __future__ import annotations

import json
import math
from collections import defaultdict
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path

from ._toml import tomllib

import numpy as np

from .config import Config
from .models import Detection

DEFAULT_TOML = """\
# Known noise sources. Edit by hand after walking the site.
# f0_hz is the fundamental; harmonics within harmonic_tol_pct are labelled too.
# Examples (commented out because they are guesses until measured here):
# [[source]]
# name = "mains (50 Hz) ripple"
# f0_hz = 50.0
# harmonics = 5
# note = "rectified 50 Hz supply hum; appears at 100/150/200 Hz"
"""


@dataclass
class KnownSource:
    name: str
    f0_hz: float
    harmonics: int = 1
    tol_pct: float = 1.0
    note: str = ""
    freqs: list[float] = field(default_factory=list)


def upsert_known(path: str | Path, name: str, f0_hz: float, tol_pct: float = 1.0,
                 harmonics: int = 5, note: str = "") -> Path:
    """Append (never rewrite) one source to the library — it is a hand-edited file (FR-7.3)."""
    p = Path(path)
    if not p.exists():
        p.write_text(DEFAULT_TOML, encoding="utf-8")
    block = (f"\n[[source]]\nname = {json.dumps(name)}\nf0_hz = {float(f0_hz):g}\n"
             f"harmonics = {int(harmonics)}\ntol_pct = {float(tol_pct):g}\n")
    if note:
        block += f"note = {json.dumps(note)}\n"
    with p.open("a", encoding="utf-8") as fh:
        fh.write(block)
    return p


def load_known(path: str | Path | None = None) -> list[KnownSource]:
    """Read a known-source TOML; a missing file simply means 'nothing known yet' (FR-7.3)."""
    if path is None:
        return []
    p = Path(path)
    if not p.exists():
        return []
    with p.open("rb") as fh:
        data = tomllib.load(fh)
    out = []
    for e in data.get("source", []):
        f0 = float(e["f0_hz"])
        n = int(e.get("harmonics", 1))
        out.append(KnownSource(name=str(e.get("name", f"source@{f0:g}")), f0_hz=f0,
                               harmonics=n, tol_pct=float(e.get("tol_pct", 1.0)),
                               note=str(e.get("note", "")),
                               freqs=[f0 * k for k in range(1, max(1, n) + 1)]))
    return out


def label(dets: list[Detection], known: list[KnownSource]) -> int:
    """Attach known-source names in place; returns how many detections matched (FR-7.3)."""
    if not known:
        return 0
    n = 0
    for d in dets:
        for k in known:
            hit = next((f for f in k.freqs if f > 0
                        and abs(d.freq_hz - f) <= max(k.tol_pct / 100.0 * f, 0.75)), None)
            if hit is not None:
                d.known_name = k.name
                d.extra["known"] = {"name": k.name, "expected_hz": round(hit, 3),
                                    "harmonic": max(1, round(hit / k.f0_hz)),
                                    "error_hz": round(d.freq_hz - hit, 3), "note": k.note}
                n += 1
                break
    return n


def recurrence(dets: list[Detection], cfg: Config) -> dict:
    """Per frequency cluster: episode inter-arrival period, phase-of-day, day coverage (FR-7.2)."""
    timed = [d for d in dets if d.t_start_wall]
    if not timed:
        return {"clusters": [], "note": "no wall-clock timestamps; recurrence not computable"}
    clusters: dict[tuple, list[Detection]] = {}
    for d in sorted(timed, key=lambda d: d.freq_hz):
        # An A4 event's freq_hz is its band's geometric centre (24 Hz for the 20-29 Hz band), not a
        # measured tone.  Two consequences: events cluster by band identity, and a tone must never
        # be merged into a band cluster (a real 28.99 Hz tone joined the 20-29 Hz impact band and
        # the row read "classes A2,A4", which is two different phenomena wearing one label).
        ev = d.cls in ("A3", "A4")
        key = (("band", d.extra.get("band_index", -1), tuple(d.extra.get("band", (0, 0))))
               if ev else ("freq", round(d.freq_hz, 2)))
        placed = False
        if not ev:
            for k, c in clusters.items():
                if k[0] == "band":
                    continue
                centre = c[0].freq_hz
                if abs(d.freq_hz - centre) <= max(cfg.recurrence_tol_hz,
                                                  cfg.recurrence_tol_pct / 100.0 * centre):
                    c.append(d)
                    placed = True
                    break
        elif not placed:
            if key not in clusters:
                clusters[key] = []
            clusters[key].append(d)
            placed = True
        if not placed:
            clusters.setdefault(key, []).append(d)

    out = []
    days: set[str] = set()
    for c in clusters.values():
        stamps = sorted(datetime.fromisoformat(d.t_start_wall) for d in c)
        days.update(s.date().isoformat() for s in stamps)
        if len(stamps) < 2:
            continue
        t0 = stamps[0].timestamp()
        times = np.array([(s.timestamp() - t0) for s in stamps], dtype=np.float64)
        gaps = np.diff(times)
        period = float(np.median(gaps)) if gaps.size else float("nan")
        # hour-of-day clustering, on the circular mean: 23:50 and 00:10 are 20 minutes apart,
        # not 23 hours, and a shift-change noise must not be split by midnight.
        hours = np.array([s.hour + s.minute / 60.0 + s.second / 3600.0 for s in stamps])
        ang = 2 * math.pi * hours / 24.0
        mean_ang = math.atan2(np.sin(ang).mean(), np.cos(ang).mean()) % (2 * math.pi)
        mean_hour = mean_ang * 24.0 / (2 * math.pi)
        r = float(np.hypot(np.cos(ang).mean(), np.sin(ang).mean()))     # 1 = all at one hour
        spread_h = (1.0 - r) * 12.0 / math.pi                           # circular std, in hours
        out.append({
            "freq_hz": round(float(np.median([d.freq_hz for d in c])), 2),
            "kind": ("event-band" if c[0].cls in ("A3", "A4") else "tone"),
            "band_hz": [round(float(b), 1) for b in c[0].extra.get("band", [])] or None,
            "n_episodes": len(stamps),
            "files": len({d.file for d in c}),
            "class": sorted({d.cls for d in c}),
            "median_gap_s": round(period, 1) if np.isfinite(period) else None,
            "gap_jitter_s": round(float(np.std(gaps)), 1) if gaps.size > 1 else None,
            "phase_of_day_hour": round(mean_hour, 3),
            "phase_spread_h": round(spread_h, 3),
            "phase_concentration": round(r, 3),
            "first": stamps[0].isoformat(), "last": stamps[-1].isoformat(),
            "known_name": next((d.known_name for d in c if d.known_name), ""),
        })
    out.sort(key=lambda c: (-c["n_episodes"], c["freq_hz"]))
    note = ""
    if len(days) < 2:
        note = (f"single-day corpus ({len(days)} day): day-of-week correlation is not "
                f"computable, only hour-of-day clustering")
    return {"clusters": out, "days": sorted(days), "note": note,
            "min_episodes": cfg.recurrence_min_episodes}
